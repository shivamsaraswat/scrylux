import { deriveRisk, ELEMENT_TYPES, MITIGATION_STATUSES, STRIDE_CATEGORIES, THREAT_STATUSES } from '@specter/core';
import type { ExportedFile } from '../../src/exchange/specter-export.js';
import type { Finding } from '../dogfood/checks.js';

// The demo's own checks, D4 and D6 of contracts/checks.md (spec FR-023, FR-024). The rest of what the demo is held to (the
// published schema, the import with nothing left out, the round trip, the ties, stale threats, the secret patterns) is
// Milestone 7's, reused as it is by demo.test.ts. Every function here takes what it needs and returns findings: none reads a
// file or calls the app, so each can be shown to fail on an input made to break it (checks.test.ts).
//
// A message names a kind of thing that is missing, or a threat by its title. It never repeats a description, a reason or a
// value the file holds.

export const DEMO_FOLDER = 'docs/demo';
export const DEMO_FILE = `${DEMO_FOLDER}/notes-app.specter.json`;
export const DEMO_FOLDER_NAMES: readonly string[] = ['README.md', 'notes-app.specter.json'];

const WHERE_TO_READ = 'See "Updating the demo" in docs/demo/README.md.';

const finding = (check: string, file: string, message: string, fix: string): Finding => ({ check, file, message, fix });

// The two lines of a failure: where, which check and what is wrong; then the smallest thing to do.
export function formatDemoFinding({ file, check, message, fix }: Finding): string {
  return `${file}: ${check}: ${message}.\nFix: ${fix}. ${WHERE_TO_READ}`;
}

// The line of a warning: the build passes, and the reader is told how to catch the demo up with the rules.
export function formatDemoWarning({ message }: Finding): string {
  return `The demo threat model is behind the rules: ${message}. The build passes.\nUpdate docs/demo/ in this or a later change. ${WHERE_TO_READ}`;
}

// The quickstart file and the documents say the app is published on 127.0.0.1. That is not the address of a deployment, so it is
// set aside before the secret-pattern scan (D7); any other address, and every other pattern, still counts. The look-arounds keep
// 127.0.0.15 and 1127.0.0.1 in the scan.
export function withoutLoopback(text: string): string {
  return text.replace(/(?<![\w.])127\.0\.0\.1(?![\w.])/g, 'loopback');
}

const words = (value: string): string => value.replaceAll('_', ' ');
const FICTIONAL = /fictional/i;

// What FR-024 says the demo contains, and what its names must say. `file` is only used to name it in a finding.
export function checkDemoShape(file: string, data: ExportedFile): Finding[] {
  const fix = 'correct it in Specter and export the demo again';
  const findings: Finding[] = [];
  const add = (message: string): void => {
    findings.push(finding('shape', file, message, fix));
  };

  if (!FICTIONAL.test(data.project.name)) add('the project name does not say that the demo is fictional');
  if (!FICTIONAL.test(data.threat_model.name)) add('the threat model name does not say that the demo is fictional');
  const methodology: string = data.threat_model.methodology;
  if (methodology !== 'STRIDE') add(`the methodology is ${methodology}, not STRIDE`);
  if (data.threat_model.status === 'draft') add('the threat model status is draft; the demo is exported as in_review or approved, to show the lifecycle');

  for (const type of ELEMENT_TYPES) {
    if (!data.elements.some((element) => element.type === type)) add(`no ${words(type)} on the diagram`);
  }

  const byId = new Map(data.elements.map((element) => [element.id, element]));
  const boundaries = new Set(data.elements.filter((element) => element.type === 'trust_boundary').map((element) => element.id));
  if (!data.elements.some((element) => element.parent_boundary_id !== null && boundaries.has(element.parent_boundary_id))) {
    add('no trust boundary holds an element');
  }

  const parentOf = (id: string | null): string | null => (id === null ? null : (byId.get(id)?.parent_boundary_id ?? null));
  const crossing = data.elements.filter((element) => element.type === 'data_flow' && parentOf(element.source_element_id) !== parentOf(element.target_element_id));
  if (crossing.length === 0) add('no data flow crosses a trust boundary');
  else if (!crossing.some((flow) => Object.keys((flow.properties.flags as Record<string, unknown> | undefined) ?? {}).length > 0)) {
    add('no data flow that crosses a trust boundary has a security flag set');
  }

  if (data.threats.some((threat) => threat.origin === 'ai')) add('a threat is AI-drafted, and the demo holds none');
  if (!data.threats.some((threat) => threat.origin === 'rule')) add('no threat was generated by the rules');
  if (!data.threats.some((threat) => threat.origin === 'manual')) add('no threat was written by hand');

  for (const category of STRIDE_CATEGORIES) {
    if (!data.threats.some((threat) => threat.category === category)) add(`no threat has the category ${category}`);
  }
  for (const status of THREAT_STATUSES) {
    if (!data.threats.some((threat) => threat.status === status)) add(`no threat is ${words(status)}`);
  }

  const risks = new Set(data.threats.map((threat) => deriveRisk(threat.likelihood, threat.impact)));
  if (risks.size < 3) add(`fewer than three risk levels among the threats (${risks.size})`);

  const supported = new Set(data.mitigations.filter((m) => m.status === 'implemented' || m.status === 'verified').map((m) => m.threat_id));
  for (const threat of data.threats) {
    if ((threat.status === 'accepted' || threat.status === 'not_applicable') && (threat.status_reason ?? '').trim() === '') {
      add(`the ${words(threat.status)} threat "${threat.title}" has no reason`);
    }
    if (threat.status === 'mitigated' && !supported.has(threat.id)) {
      add(`the mitigated threat "${threat.title}" has no implemented or verified mitigation`);
    }
  }
  for (const status of MITIGATION_STATUSES) {
    if (!data.mitigations.some((mitigation) => mitigation.status === status)) add(`no mitigation is ${status}`);
  }

  return findings;
}

// The folder holds the demo file and its description, and nothing else (FR-023).
export function checkDemoFolder(names: readonly string[]): Finding[] {
  const findings: Finding[] = [];
  for (const name of names) {
    if (!DEMO_FOLDER_NAMES.includes(name)) {
      findings.push(finding('folder', `${DEMO_FOLDER}/${name}`, `the folder holds ${name}, which is neither the demo nor its description`, `remove ${name} from ${DEMO_FOLDER}/`));
    }
  }
  for (const name of DEMO_FOLDER_NAMES) {
    if (!names.includes(name)) {
      findings.push(finding('folder', `${DEMO_FOLDER}/${name}`, `${name} is missing from the folder`, `add ${name}: build and export the demo, or restore the description`));
    }
  }
  return findings;
}
